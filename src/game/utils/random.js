// Deterministic pseudo-random number generator (mulberry32) so the city
// layout is stable across nights but still feels hand-rolled.

export function createRng(seed) {
  let a = seed >>> 0;
  return function rng() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function pick(rng, arr) {
  return arr[Math.floor(rng() * arr.length)];
}

export function range(rng, min, max) {
  return min + rng() * (max - min);
}

export function chance(rng, probability) {
  return rng() < probability;
}

/** Picks an index from `weights` proportionally to its value (all-equal weights degrades to a uniform pick). */
export function pickWeightedIndex(rng, weights) {
  const total = weights.reduce((sum, w) => sum + w, 0);
  if (total <= 0) return Math.floor(rng() * weights.length);
  let r = rng() * total;
  for (let i = 0; i < weights.length; i++) {
    if (r < weights[i]) return i;
    r -= weights[i];
  }
  return weights.length - 1;
}
